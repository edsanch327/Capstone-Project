import express from "express";
import dotenv from "dotenv";
import bcrypt from "bcryptjs";
import jwt from "jsonwebtoken";
import pg from "pg";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
dotenv.config({ path: path.join(root, ".env") });

if (!process.env.JWT_SECRET || process.env.JWT_SECRET.length < 32) {
    console.error("Set a secure JWT_SECRET (32+ characters) in .env before starting the backend.");
    process.exit(1);
}

const { Pool } = pg;
const db = new Pool({
    connectionString: process.env.DATABASE_URL,
    ssl: process.env.PGSSL === "true" ? { rejectUnauthorized: true } : undefined
});

if (!process.env.DATABASE_URL) {
    console.error("Set DATABASE_URL in .env before starting the backend.");
    process.exit(1);
}
// Create the PostgreSQL tables before accepting requests.
async function initializeDatabase() {
    await db.query(`
        CREATE TABLE IF NOT EXISTS users (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL,
            email VARCHAR(255) NOT NULL UNIQUE,
            password_hash TEXT NOT NULL
        );

        CREATE TABLE IF NOT EXISTS appointments (
            id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            service TEXT NOT NULL,
            stylist VARCHAR(255) NOT NULL,
            date DATE NOT NULL,
            time VARCHAR(255) NOT NULL,
            CONSTRAINT unique_stylist_date_time UNIQUE (stylist, date, time)
        );
    `);
}

const app = express();
app.use(express.json({ limit: "20kb" }));

function asyncHandler(handler) {
    return (req, res, next) => Promise.resolve(handler(req, res, next)).catch(next);
}

function createToken(user) {
    return jwt.sign({ id: user.id }, process.env.JWT_SECRET, { expiresIn: "7d" });
}

function publicUser(user) {
    return { id: user.id, name: user.name, email: user.email };
}

async function requireAuth(req, res, next) {
    const token = req.headers.authorization?.replace(/^Bearer /, "");

    try {
        const payload = jwt.verify(token, process.env.JWT_SECRET);
        const { rows } = await db.query("SELECT id, name, email FROM users WHERE id = $1", [payload.id]);
        const user = rows[0];
        if (!user) return res.status(401).json({ error: "Account not found." });
        req.user = user;
        next();
    } catch {
        return res.status(401).json({ error: "Please log in again." });
    }
}

app.get("/api/health", (req, res) => res.json({ status: "ok" }));

app.post("/api/auth/register", async (req, res) => {
    const name = String(req.body?.name || "").trim();
    const email = String(req.body?.email || "").trim().toLowerCase();
    const password = req.body?.password;

    if (!name || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email) || typeof password !== "string" || password.length < 8) {
        return res.status(400).json({ error: "Enter your name, a valid email, and a password of at least 8 characters." });
    }

    const passwordHash = await bcrypt.hash(password, 12);

    try {
        const result = await db.query("INSERT INTO users (name, email, password_hash) VALUES ($1, $2, $3) RETURNING id", [name, email, passwordHash]);
        const user = { id: result.rows[0].id, name, email };
        return res.status(201).json({ user, token: createToken(user) });
    } catch (error) {
        if (error.code === "23505") {
            return res.status(409).json({ error: "An account with this email already exists." });
        }
        console.error(error);
        return res.status(500).json({ error: "Could not create your account." });
    }
});

app.post("/api/auth/login", asyncHandler(async (req, res) => {
    const email = String(req.body?.email || "").trim().toLowerCase();
    const password = req.body?.password;
    const { rows } = await db.query("SELECT * FROM users WHERE email = $1", [email]);
    const user = rows[0];

    if (!user || typeof password !== "string" || !(await bcrypt.compare(password, user.password_hash))) {
        return res.status(401).json({ error: "Incorrect email or password." });
    }

    return res.json({ user: publicUser(user), token: createToken(user) });
}));

app.get("/api/auth/me", requireAuth, (req, res) => res.json({ user: req.user }));

app.get("/api/appointments", requireAuth, async (req, res) => {
    try {
        const { rows } = await db.query("SELECT id, service, stylist, TO_CHAR(date, 'YYYY-MM-DD') AS date, time FROM appointments WHERE user_id = $1 ORDER BY date, time", [req.user.id]);
        res.json({ appointments: rows });
    } catch (error) {
        console.error(error);
        res.status(500).json({ error: "Could not load appointments." });
    }
});

app.post("/api/appointments", requireAuth, async (req, res) => {
    const { service, stylist, date, time } = req.body || {};
    const services = ["Signature Cut", "Colour Ritual", "Gloss & Tone", "Blowout & Style"];
    const stylists = ["Alex Morgan", "Jordan Lee", "Taylor Reed"];
    const times = ["09:00", "10:00", "11:00", "12:00", "13:00", "14:00", "15:00", "16:00"];
    const validDate = typeof date === "string" && /^\d{4}-\d{2}-\d{2}$/.test(date) && !Number.isNaN(Date.parse(date)) && new Date(`${date}T23:59:59`) >= new Date();

    if (!services.includes(service) || !stylists.includes(stylist) || !validDate || !times.includes(time)) {
        return res.status(400).json({ error: "Choose a valid service, stylist, date, and time." });
    }

    try {
        const result = await db.query("INSERT INTO appointments (user_id, service, stylist, date, time) VALUES ($1, $2, $3, $4, $5) RETURNING id", [req.user.id, service, stylist, date, time]);
        return res.status(201).json({ id: result.rows[0].id });
    } catch (error) {
        if (error.code === "23505") {
            return res.status(409).json({ error: "That stylist is already booked at that time." });
        }
        console.error(error);
        return res.status(500).json({ error: "Could not save your appointment." });
    }
});

app.delete("/api/appointments/:id", requireAuth, async (req, res) => {
    try {
        const result = await db.query("DELETE FROM appointments WHERE id = $1 AND user_id = $2", [req.params.id, req.user.id]);
        if (!result.rowCount) return res.status(404).json({ error: "Appointment not found." });
        return res.json({ success: true });
    } catch (error) {
        console.error(error);
        return res.status(500).json({ error: "Could not cancel appointment." });
    }
});

app.use((error, req, res, next) => {
    console.error(error);
    if (!res.headersSent) res.status(500).json({ error: "An unexpected server error occurred." });
});

const port = Number(process.env.PORT || 3001);
initializeDatabase()
    .then(() => app.listen(port, () => console.log(`Beauty Calendar API running at http://localhost:${port}`)))
    .catch((error) => {
        console.error("Could not connect to PostgreSQL:", error);
        process.exit(1);
    });
